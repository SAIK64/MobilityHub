package projet.saik.model;

//API java.time pour gérer les dates et heures
import java.time.LocalDate;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;

@Entity
@Table(name = "expenses")
public class Expense {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false)
    private String description;

    @Column(nullable = false)
    private Double amount;

    //pas de column alors sans contrainte de nullité, peut être null
    private String category;
    //converti par hibernate en type date dans la base de données, peut être null
    private LocalDate expenseDate;

    @Column(nullable = false)
    private Boolean isAutoGenerated = false;

    //Un budget peut avoir plusieurs dépenses, mais une dépense appartient à un seul budget
    //fetch = FetchType.LAZY pour que la récupération du budget associé à une dépense ne se fasse que si nécessaire, ce qui améliore les performances
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "budget_id", nullable = false)
    private Budget budget;

    //Une dépense peut être associée à un seul billet de transport, et un billet de transport peut générer une seule dépense
    //mappedBy = "generatedExpense" pour indiquer que la relation est bidirectionnelle et que la propriété "generatedExpense" de TransportTicket est le propriétaire de la relation
    @OneToOne(mappedBy = "generatedExpense")
    private TransportTicket transportTicket;

    public Expense() {}

    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }

    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }

    public Double getAmount() { return amount; }
    public void setAmount(Double amount) { this.amount = amount; }

    public String getCategory() { return category; }
    public void setCategory(String category) { this.category = category; }

    public LocalDate getExpenseDate() { return expenseDate; }
    public void setExpenseDate(LocalDate expenseDate) { this.expenseDate = expenseDate; }

    public Boolean getIsAutoGenerated() { return isAutoGenerated; }
    public void setIsAutoGenerated(Boolean isAutoGenerated) { this.isAutoGenerated = isAutoGenerated; }

    public Budget getBudget() { return budget; }
    public void setBudget(Budget budget) { this.budget = budget; }

    public TransportTicket getTransportTicket() { return transportTicket; }
    public void setTransportTicket(TransportTicket transportTicket) { this.transportTicket = transportTicket; }
}