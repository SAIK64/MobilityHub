package projet.saik.model;

//API java.time pour gérer les dates et heures
import java.time.LocalDate;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;

//Entity représente une table dans la base de données, Table spécifie le nom de la table
@Entity
@Table(name = "expenses")
// Entité représentant une dépense rattachée au budget d’un voyage.
public class Expense {

    //@Id indique que c'est la clé primaire
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;
    
    //description est obligatoire et unique, ne peut pas être null
    @Column(nullable = false, unique = true)
    private String description;

    @Column(nullable = false)
    private Double amount;

    //pas de column alors sans contrainte de nullité, peut être null
    private String category;
    //converti par hibernate en type date dans la base de données, peut être null
    private LocalDate expenseDate;
    private String paymentMethod;
    // nom du justificatif sélectionné ; le fichier lui-même n’est pas stocké ici.
    private String receiptName;

    // distingue une dépense créée par un billet d’une dépense saisie à la main.
    // false signifie que la dépense est saisie par l'utilisateur
    @Column(nullable = false)
    private Boolean isAutoGenerated = false;

    //Un budget peut avoir plusieurs dépenses, mais une dépense appartient à un seul budget
    //fetch = FetchType.LAZY pour que la récupération du budget associé à une dépense ne se fasse que si nécessaire, ce qui améliore les performances
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "budget_id", nullable = false)
    private Budget budget;

    //Une dépense peut être associée à un seul billet de transport, et un billet de transport peut générer une seule dépense
    //mappedBy = "generatedExpense" pour indiquer que la propriété "generatedExpense" de TransportTicket est le propriétaire de la relation
    @OneToOne(mappedBy = "generatedExpense")
    private TransportTicket transportTicket;

    public Expense() {}

    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }

    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }

    public Double getAmount() { return amount; }
    public void setAmount(Double amount) { this.amount = amount; }

    public String getCategory() { return category; }
    public void setCategory(String category) { this.category = category; }

    public LocalDate getExpenseDate() { return expenseDate; }
    public void setExpenseDate(LocalDate expenseDate) { this.expenseDate = expenseDate; }

    // Retourne le moyen de paiement enregistré.
    public String getPaymentMethod() { return paymentMethod; }
    // Met à jour le moyen de paiement associé à la dépense.
    public void setPaymentMethod(String paymentMethod) { this.paymentMethod = paymentMethod; }

    // Retourne le nom du justificatif associé.
    public String getReceiptName() { return receiptName; }
    // Enregistre le nom du justificatif sans téléverser son contenu.
    public void setReceiptName(String receiptName) { this.receiptName = receiptName; }

    public Boolean getIsAutoGenerated() { return isAutoGenerated; }
    public void setIsAutoGenerated(Boolean isAutoGenerated) { this.isAutoGenerated = isAutoGenerated; }

    public Budget getBudget() { return budget; }
    public void setBudget(Budget budget) { this.budget = budget; }

    public TransportTicket getTransportTicket() { return transportTicket; }
    public void setTransportTicket(TransportTicket transportTicket) { this.transportTicket = transportTicket; }
}